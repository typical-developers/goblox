package legacy

import (
	"context"
	"fmt"
	"net/http"

	"github.com/typical-developers/goblox"
	"github.com/typical-developers/goblox/auth"
)

const (
	MaxThumbnailBatchSize = 100
)

var (
	GetBatchThumbnails = goblox.NewEndpoint(
		http.MethodPost,
		"/v1/batch",
		auth.KindCookie, auth.KindNone,
	).WithDomain("thumbnails")
)

type ThumbnailsService service

type ThumbnailType string

const (
	ThumbnailTypeAvatar                     ThumbnailType = "Avatar"
	ThumbnailTypeAvatarHeadShot             ThumbnailType = "AvatarHeadShot"
	ThumbnailTypeAvatarBust                 ThumbnailType = "AvatarBust"
	ThumbnailTypeGameIcon                   ThumbnailType = "GameIcon"
	ThumbnailTypeGameThumbnail              ThumbnailType = "GameThumbnail"
	ThumbnailTypePlaceIcon                  ThumbnailType = "PlaceIcon"
	ThumbnailTypeBadgeIcon                  ThumbnailType = "BadgeIcon"
	ThumbnailTypeGamePass                   ThumbnailType = "GamePass"
	ThumbnailTypeDeveloperProduct           ThumbnailType = "DeveloperProduct"
	ThumbnailTypeAsset                      ThumbnailType = "Asset"
	ThumbnailTypeBundleThumbnail            ThumbnailType = "BundleThumbnail"
	ThumbnailTypeOutfit                     ThumbnailType = "Outfit"
	ThumbnailTypeGroupIcon                  ThumbnailType = "GroupIcon"
	ThumbnailTypeLook                       ThumbnailType = "Look"
	ThumbnailTypeScreenshot                 ThumbnailType = "Screenshot"
	ThumbnailTypeCreatorContextAsset        ThumbnailType = "CreatorContextAsset"
	ThumbnailTypeAutoGeneratedAsset         ThumbnailType = "AutoGeneratedAsset"
	ThumbnailTypeAutoGeneratedGameIcon      ThumbnailType = "AutoGeneratedGameIcon"
	ThumbnailTypeForceAutoGeneratedGameIcon ThumbnailType = "ForceAutoGeneratedGameIcon"
)

type ThumbnailSize string

type ThumbnailFormat string

var (
	ThumbnailFormatPng  ThumbnailFormat = "Png"
	ThumbnailFormatJpeg ThumbnailFormat = "Jpeg"
	ThumbnailFormatWebp ThumbnailFormat = "Webp"
	ThumbnailFormatIco  ThumbnailFormat = "Ico"  // Only available on places.
	ThumbnailFormatIcns ThumbnailFormat = "Icns" // Only available on places.
)

type ThumbnailBatch struct {
	RequestID           string          `json:"requestId,omitempty"`
	TargetID            int64           `json:"targetId,omitempty"`
	Token               string          `json:"token,omitempty"`
	Alias               string          `json:"alias,omitempty"`
	Type                ThumbnailType   `json:"type"`
	Size                ThumbnailSize   `json:"size,omitempty"`
	Format              ThumbnailFormat `json:"format,omitempty"`
	IsCircular          bool            `json:"isCircular,omitempty"`
	IncludeBackground   bool            `json:"includeBackground,omitempty"`
	IncludeProfileFrame bool            `json:"includeProfileFrame,omitempty"`
	AccessContext       string          `json:"accessContext,omitempty"`
	HeadShape           string          `json:"headShape,omitempty"`
}

type ThumbnailState string

const (
	ThumbnailStateCompleted              ThumbnailState = "Completed"
	ThumbnailStatePending                ThumbnailState = "Pending"
	ThumbnailStateInReview               ThumbnailState = "InReview"
	ThumbnailStateBlocked                ThumbnailState = "Blocked"
	ThumbnailStateError                  ThumbnailState = "Error"
	ThumbnailStateTemporarilyUnavailable ThumbnailState = "TemporarilyUnavailable"
)

type ThumbnailBatchResult struct {
	RequestID    string         `json:"requestId"`
	TargetID     int64          `json:"targetId"`
	State        ThumbnailState `json:"state"`
	ImageURL     *string        `json:"imageUrl"`
	Version      string         `json:"version"`
	ErrorCode    int            `json:"errorCode"`
	ErrorMessage string         `json:"errorMessage"`
}

// Batch will get the thumbnails for a batch of assets.
//
// [POST] https://thumbnails.roblox.com/v1/batch
func (t *ThumbnailsService) Batch(ctx context.Context, batch []ThumbnailBatch, opts ...goblox.RequestOpt) ([]ThumbnailBatchResult, *Response, error) {
	if len(batch) == 0 {
		return nil, nil, nil
	}
	if len(batch) > MaxThumbnailBatchSize {
		return nil, nil, fmt.Errorf("goblox: batch size exceeds maximum of %d", MaxThumbnailBatchSize)
	}

	results := new(WrappedResponse[[]ThumbnailBatchResult])
	resp, err := t.client.Call(ctx, GetBatchThumbnails.Compile(nil), batch, results, opts...)
	if err != nil {
		return nil, resp, err
	}

	return results.Data, resp, nil
}
