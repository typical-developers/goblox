// getThumbnails calls an endpoint that returns a wrapped list of thumbnails.
func (t *ThumbnailsService) getThumbnails(ctx context.Context, e *goblox.CompiledEndpoint, opts []goblox.RequestOpt) ([]Thumbnail, *Response, error) {
	results := new(WrappedResponse[[]Thumbnail])
	resp, err := t.client.Call(ctx, e, nil, results, opts...)
	if err != nil {
		return nil, resp, err
	}

	return results.Data, resp, nil
}

// getThumbnail calls an endpoint that returns a single thumbnail.
func (t *ThumbnailsService) getThumbnail(ctx context.Context, e *goblox.CompiledEndpoint, opts []goblox.RequestOpt) (*Thumbnail, *Response, error) {
	thumbnail := new(Thumbnail)
	resp, err := t.client.Call(ctx, e, nil, thumbnail, opts...)
	if err != nil {
		return nil, resp, err
	}

	return thumbnail, resp, nil
}

// withPlaceID adds the Roblox-Place-Id header when placeID is set.
func withPlaceID(opts []goblox.RequestOpt, placeID *int64) []goblox.RequestOpt {
	if placeID != nil {
		opts = append(opts, goblox.WithHeader("Roblox-Place-Id", fmt.Sprint(*placeID)))
	}

	return opts
}

